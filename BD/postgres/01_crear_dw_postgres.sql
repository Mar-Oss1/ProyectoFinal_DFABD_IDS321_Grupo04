/* ============================================================
   01 · CREACIÓN DEL DATA WAREHOUSE EN POSTGRESQL (esquema estrella)
   Equivalente de BD/01_crear_dw.sql (SQL Server).
   Ejecutar conectado a la base openflightsdw (pgAdmin: Query Tool sobre esa base).
   RE-EJECUTABLE: SÍ (IF NOT EXISTS + ON CONFLICT DO NOTHING)

   Diferencias con la versión SQL Server (para la matriz comparativa):
   - Nombres sin comillas: PostgreSQL los guarda en minúsculas (DimFecha -> dimfecha).
   - NVARCHAR -> VARCHAR (la base es UTF-8, todo texto es Unicode).
   - TINYINT no existe -> SMALLINT.  BIT -> BOOLEAN.  DATETIME2 -> TIMESTAMP.
   - IDENTITY(-1,1) + SET IDENTITY_INSERT -> GENERATED BY DEFAULT AS IDENTITY,
     que acepta insertar el -1 explícito sin activar nada.
   - Guardas IF OBJECT_ID / sys.indexes -> CREATE ... IF NOT EXISTS.
   - Calendario con generate_series en lugar de ROW_NUMBER sobre sys.columns.
   - Día de la semana con EXTRACT(ISODOW): 1 = lunes ... 7 = domingo, sin depender
     de la configuración del idioma (en SQL Server hizo falta una fórmula con DATEDIFF).
   - ICAO único: en SQL Server UNIQUE admite un solo NULL, por eso se usó índice
     filtrado (WHERE ICAO IS NOT NULL). En PostgreSQL varios NULL no chocan,
     así que basta un índice único normal.
   - No hay GO: cada sentencia termina en ;
   ============================================================ */

/* ---------- DimFecha: calendario GENERADO 2019-2020 (731 días) ---------- */
CREATE TABLE IF NOT EXISTS dimfecha (
    fechakey      INT         PRIMARY KEY,
    fecha         DATE        NOT NULL,
    anio          INT         NOT NULL,
    trimestre     INT         NOT NULL,
    mes           INT         NOT NULL,
    nombremes     VARCHAR(50),
    dia           INT         NOT NULL,
    nombredia     VARCHAR(50),
    esfindesemana BOOLEAN     NOT NULL,
    diasemana     SMALLINT    NOT NULL   -- 1 = lunes ... 7 = domingo (ISO)
);

INSERT INTO dimfecha (fechakey, fecha, anio, trimestre, mes, nombremes,
                      dia, nombredia, esfindesemana, diasemana)
SELECT TO_CHAR(g.d, 'YYYYMMDD')::INT,
       g.d::DATE,
       EXTRACT(YEAR    FROM g.d)::INT,
       EXTRACT(QUARTER FROM g.d)::INT,
       EXTRACT(MONTH   FROM g.d)::INT,
       (ARRAY['Enero','Febrero','Marzo','Abril','Mayo','Junio','Julio',
              'Agosto','Septiembre','Octubre','Noviembre','Diciembre'])[EXTRACT(MONTH FROM g.d)::INT],
       EXTRACT(DAY     FROM g.d)::INT,
       (ARRAY['Lunes','Martes','Miércoles','Jueves','Viernes','Sábado','Domingo'])[EXTRACT(ISODOW FROM g.d)::INT],
       EXTRACT(ISODOW  FROM g.d) IN (6, 7),
       EXTRACT(ISODOW  FROM g.d)::SMALLINT
FROM generate_series(DATE '2019-01-01', DATE '2020-12-31', INTERVAL '1 day') AS g(d)
ON CONFLICT (fechakey) DO NOTHING;

/* ---------- DimHora: 24 horas UTC (PrimeraVista de OpenSky viene en UTC) ---------- */
CREATE TABLE IF NOT EXISTS dimhora (
    hora    SMALLINT    PRIMARY KEY,
    horautc VARCHAR(10) NOT NULL
);

INSERT INTO dimhora (hora, horautc)
SELECT h, LPAD(h::TEXT, 2, '0') || ':00 UTC'
FROM generate_series(0, 23) AS h
ON CONFLICT (hora) DO NOTHING;

/* ---------- DimAeropuerto: maestro OurAirports + complemento OpenFlights ---------- */
CREATE TABLE IF NOT EXISTS dimaeropuerto (
    aeropuertokey      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bk_ident           VARCHAR(20)  NOT NULL UNIQUE,
    icao               VARCHAR(4),
    iata               VARCHAR(5),
    nombre             VARCHAR(200),
    ciudad             VARCHAR(100),
    codigopais         CHAR(2),
    paisnombre         VARCHAR(200),
    regioncodigo       VARCHAR(16),
    regionnombre       VARCHAR(200),
    continente         CHAR(2),
    latitud            NUMERIC(11,7),
    longitud           NUMERIC(11,7),
    elevationft        INT,
    tipoaeropuerto     VARCHAR(50),
    servicioprogramado VARCHAR(30),
    zonahoraria        VARCHAR(50),
    origenfuente       VARCHAR(12)  NOT NULL DEFAULT 'OurAirports'
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dimaeropuerto_icao ON dimaeropuerto (icao);

/* ---------- DimAerolinea: maestro OpenFlights ---------- */
CREATE TABLE IF NOT EXISTS dimaerolinea (
    aerolineakey INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bk_airlineid INT          NOT NULL UNIQUE,
    nombre       VARCHAR(200),
    alias        VARCHAR(200),
    iata         VARCHAR(5),
    icao         VARCHAR(4),
    callsign     VARCHAR(50),
    pais         VARCHAR(100),
    activa       VARCHAR(2)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_dimaerolinea_icao ON dimaerolinea (icao);

/* ---------- DimAvion: OpenSky (typecode) + rutas OpenFlights (equipment) ---------- */
CREATE TABLE IF NOT EXISTS dimavion (
    avionkey       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bk_codigotipo  VARCHAR(30) NOT NULL UNIQUE,
    origenregistro VARCHAR(20)
);

/* ---------- FactVuelos: grano = 1 vuelo real ADS-B ---------- */
CREATE TABLE IF NOT EXISTS factvuelos (
    vuelokey                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fechakey                INT          NOT NULL REFERENCES dimfecha (fechakey),
    horasalida              SMALLINT     NOT NULL REFERENCES dimhora (hora),
    aerolineakey            INT          NOT NULL REFERENCES dimaerolinea (aerolineakey),
    avionkey                INT          NOT NULL REFERENCES dimavion (avionkey),
    aeropuertoorigenkey     INT          NOT NULL REFERENCES dimaeropuerto (aeropuertokey),
    aeropuertodestinokey    INT          NOT NULL REFERENCES dimaeropuerto (aeropuertokey),
    callsign                VARCHAR(20),
    aircraftuid             VARCHAR(40),
    primeravista            TIMESTAMP(0) NOT NULL,
    ultimavista             TIMESTAMP(0) NOT NULL,
    cantidadvuelos          INT          NOT NULL DEFAULT 1,
    duracionminutos         INT,
    distanciakm             NUMERIC(10,2),
    esinternacional         BOOLEAN,
    esrutaofertada          BOOLEAN,
    asientosdisponibles     INT,
    pasajerosestimados      INT,
    factorocupacionestimado NUMERIC(5,4),
    ingresoestimadousd      NUMERIC(12,2),
    retrasoestimadomin      INT,
    CONSTRAINT uq_factvuelos UNIQUE (aircraftuid, primeravista)
);

/* ---------- Crosswalk de rutas ofertadas (para esrutaofertada) ---------- */
CREATE TABLE IF NOT EXISTS xw_rutas_icao (
    origen  VARCHAR(4) NOT NULL,
    destino VARCHAR(4) NOT NULL,
    CONSTRAINT pk_xw_rutas PRIMARY KEY (origen, destino)
);

/* ---------- Log de carga: evidencia de ejecución del ETL ---------- */
CREATE TABLE IF NOT EXISTS logcarga (
    logid              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio             TIMESTAMP,
    fin                TIMESTAMP,
    filasdimaeropuerto INT,
    filasdimaerolinea  INT,
    filasdimavion      INT,
    filasfactvuelos    INT,
    estado             VARCHAR(20),
    error              VARCHAR(500)
);

/* ---------- Miembros -1: datos de DISEÑO, no de carga ----------
   GENERATED BY DEFAULT acepta el -1 explícito; ON CONFLICT los hace re-ejecutables. */
INSERT INTO dimaeropuerto (aeropuertokey, bk_ident, nombre, origenfuente)
VALUES (-1, 'DESCONOCIDO', 'Aeropuerto no catalogado', 'N/D')
ON CONFLICT DO NOTHING;

INSERT INTO dimaerolinea (aerolineakey, bk_airlineid, nombre, activa)
VALUES (-1, -1, 'Aerolínea no identificada', 'ND')
ON CONFLICT DO NOTHING;

INSERT INTO dimavion (avionkey, bk_codigotipo, origenregistro)
VALUES (-1, 'DESC', 'N/D')
ON CONFLICT DO NOTHING;

/* ---------- Índices de la tabla de hechos ---------- */
CREATE INDEX IF NOT EXISTS ix_factvuelos_fechakey       ON factvuelos (fechakey);
CREATE INDEX IF NOT EXISTS ix_factvuelos_horasalida     ON factvuelos (horasalida);
CREATE INDEX IF NOT EXISTS ix_factvuelos_aerolineakey   ON factvuelos (aerolineakey);
CREATE INDEX IF NOT EXISTS ix_factvuelos_avionkey       ON factvuelos (avionkey);
CREATE INDEX IF NOT EXISTS ix_factvuelos_origen_destino ON factvuelos (aeropuertoorigenkey, aeropuertodestinokey);

/* ---------- Chequeo post-creación (esperado: 731 / 24 / 1 / 1 / 1 / 0 / 0 / 0) ---------- */
SELECT (SELECT COUNT(*) FROM dimfecha)      AS dim_fecha,
       (SELECT COUNT(*) FROM dimhora)       AS dim_hora,
       (SELECT COUNT(*) FROM dimaeropuerto) AS dim_aeropuerto,
       (SELECT COUNT(*) FROM dimaerolinea)  AS dim_aerolinea,
       (SELECT COUNT(*) FROM dimavion)      AS dim_avion,
       (SELECT COUNT(*) FROM factvuelos)    AS hechos,
       (SELECT COUNT(*) FROM xw_rutas_icao) AS xw_rutas,
       (SELECT COUNT(*) FROM logcarga)      AS logs;
